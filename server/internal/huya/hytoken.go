package huya

import (
	"bytes"
	"encoding/base64"
	"encoding/binary"
	"fmt"
	"strings"
	"sync/atomic"
)

const (
	// TokenTypeHyToken is the iTokenType emitted by libudbauthunify.so common_token_pack()
	// when authenticating with a packed Huya UDB biztoken.
	TokenTypeHyToken int32 = 2
)

var hyNonceCounter atomic.Uint32

// DecodeBase64Flexible decodes standard, URL-safe, or unpadded Base64 strings.
func DecodeBase64Flexible(s string) ([]byte, error) {
	trimmed := strings.TrimSpace(s)
	if trimmed == "" {
		return nil, fmt.Errorf("empty base64 string")
	}
	for _, enc := range []*base64.Encoding{
		base64.StdEncoding,
		base64.URLEncoding,
		base64.RawStdEncoding,
		base64.RawURLEncoding,
	} {
		if b, err := enc.DecodeString(trimmed); err == nil {
			return b, nil
		}
	}
	return nil, fmt.Errorf("invalid base64 payload")
}

// PackHyToken packs a raw or Base64-encoded UDB biztoken into the exact wire format
// generated by Huya Android's libudbauthunify.so (BusinessCfg::getTicketInfo ->
// hytoken_pack -> common_token_pack), suitable for HUYA.UserId.sToken with iTokenType=2.
func PackHyToken(uid uint64, appID, deviceID, bizAppID string, bizTokenB64 string, serviceTimeSec uint64) (string, error) {
	rawTok, err := DecodeBase64Flexible(bizTokenB64)
	if err != nil {
		return "", fmt.Errorf("decode biztoken: %w", err)
	}
	if bizAppID == "" {
		bizAppID = appID
	}
	return PackHyTokenRaw(uid, appID, deviceID, bizAppID, rawTok, serviceTimeSec), nil
}

// PackHyTokenRaw encodes raw biztoken bytes into the packed Base64 sToken string.
func PackHyTokenRaw(uid uint64, appID, deviceID, bizAppID string, rawBizToken []byte, serviceTimeSec uint64) string {
	counter := uint64(hyNonceCounter.Add(1)-1) & 0xFFFF
	nonce := (serviceTimeSec << 16) | counter

	var inner bytes.Buffer
	inner.WriteByte(1)                                       // version = 1
	_ = binary.Write(&inner, binary.LittleEndian, uint32(3)) // token kind = 3
	_ = binary.Write(&inner, binary.LittleEndian, uid)
	_ = binary.Write(&inner, binary.LittleEndian, nonce)
	putCredVarStr(&inner, []byte(appID))
	putCredVarStr(&inner, []byte(deviceID))
	putCredVarStr(&inner, []byte(bizAppID))
	putCredVarStr(&inner, rawBizToken)
	_ = binary.Write(&inner, binary.LittleEndian, uint32(0)) // reserved = 0

	innerBytes := inner.Bytes()
	var outer bytes.Buffer
	_ = binary.Write(&outer, binary.LittleEndian, uint16(len(innerBytes)+2))
	putCredVarStr(&outer, innerBytes)
	return base64.StdEncoding.EncodeToString(outer.Bytes())
}

func putCredVarStr(buf *bytes.Buffer, b []byte) {
	_ = binary.Write(buf, binary.LittleEndian, uint16(len(b)))
	buf.Write(b)
}
